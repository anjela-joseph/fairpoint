// Tidies punctuation and capitalisation in the saved place data, in place:
//   data/location-index.js   (location search)
//   data/kerala-statewide.js (nearby places and towns)
//   data/kerala-regions.js, data/kochi.js (regional nearby places)
// Safe to run more than once. Rebuilding the data with the build scripts tidies automatically.
import { writeFile, rename } from 'node:fs/promises';
import { LOCATION_METADATA, LOCATION_ROWS } from '../data/location-index.js';
import { KERALA_STATEWIDE } from '../data/kerala-statewide.js';
import { KERALA_REGIONS } from '../data/kerala-regions.js';
import { KOCHI_CATALOGUE } from '../data/kochi.js';
import { tidyAddress, tidyLocationRow, tidyName } from '../lib/place-names.js';

const root = new URL('../', import.meta.url);
async function save(file, text) {
  const temp = new URL(`data/${file}.tmp`, root);
  await writeFile(temp, text);
  await rename(temp, new URL(`data/${file}`, root));
}
let changed = 0;
const tidyPlace = place => {
  const name = tidyName(place.name), address = place.address ? tidyAddress(place.address) : place.address;
  if (name !== place.name || address !== place.address) changed++;
  return { ...place, name, ...(place.address !== undefined ? { address } : {}) };
};

// Location search
const rows = LOCATION_ROWS.map(row => {
  const tidy = tidyLocationRow(row);
  if (tidy[1] !== row[1] || tidy[4] !== row[4]) changed++;
  return tidy;
});
await save('location-index.js', '// Generated searchable Kerala locations. Row: id,name,lat,lon,address,aliases,kind,source.\n// OSM: ODbL 1.0; GeoNames: CC BY 4.0. See data/statewide/README.md.\nexport const LOCATION_METADATA = ' + JSON.stringify(LOCATION_METADATA) + ';\nexport const LOCATION_ROWS = JSON.parse(' + JSON.stringify(JSON.stringify(rows)) + ');\n');
const searchChanges = changed;

// Nearby places and towns
changed = 0;
const statewide = { ...KERALA_STATEWIDE, venues: KERALA_STATEWIDE.venues.map(tidyPlace), settlements: KERALA_STATEWIDE.settlements.map(tidyPlace) };
await save('kerala-statewide.js', '// Generated Kerala OSM extract. © OpenStreetMap contributors, ODbL 1.0.\nexport const KERALA_STATEWIDE = JSON.parse(' + JSON.stringify(JSON.stringify(statewide)) + ');\n');
const regions = KERALA_REGIONS.map(region => ({ ...region, venues: region.venues.map(tidyPlace) }));
await save('kerala-regions.js', '// Generated from saved Overpass data. © OpenStreetMap contributors, ODbL 1.0.\nexport const KERALA_REGIONS = ' + JSON.stringify(regions, null, 2) + ';\n');
const kochi = { ...KOCHI_CATALOGUE, venues: KOCHI_CATALOGUE.venues.map(tidyPlace) };
await save('kochi.js', '// Generated by scripts/build-kochi.mjs from saved Overpass responses.\n// OpenStreetMap contributors, ODbL 1.0. See kochi-source/README.md.\nexport const KOCHI_CATALOGUE = ' + JSON.stringify(kochi, null, 2) + ';\n');

console.log(`Tidied ${searchChanges.toLocaleString()} search locations and ${changed.toLocaleString()} nearby places and towns.`);
