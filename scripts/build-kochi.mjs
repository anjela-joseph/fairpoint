import { readdir, readFile, writeFile, rename } from 'node:fs/promises';
import { normalizeVenues } from '../lib/osm-venues.js';

const directory = new URL('../data/kochi-source/', import.meta.url);
const files = (await readdir(directory)).filter(file => file.endsWith('.json')).sort();
const snapshots = await Promise.all(files.map(async file => ({ file, ...JSON.parse(await readFile(new URL(file, directory), 'utf8')) })));
if (!snapshots.length || snapshots.some(s => s.remark || !Array.isArray(s.elements) || !s.bounds || !s.fetchedAt)) {
  throw new Error('Missing or incomplete snapshots; existing catalogue kept.');
}
// Prefer the newest OSM base timestamp when overlapping requests contain an ID.
snapshots.sort((a, b) => (b.osm3s?.timestamp_osm_base || '').localeCompare(a.osm3s?.timestamp_osm_base || '') || b.fetchedAt.localeCompare(a.fetchedAt));
const venues = normalizeVenues(snapshots.flatMap(s => s.elements)).sort((a, b) => a.id.localeCompare(b.id));
if (!venues.length) throw new Error('No real venues found; existing catalogue kept.');
const sourceDates = snapshots.map(s => s.osm3s?.timestamp_osm_base).filter(Boolean).sort();
const metadata = {
  id: 'kochi-snapshot', name: 'Saved Kochi places',
  fetchedAt: snapshots.map(s => s.fetchedAt).sort().at(-1),
  osmBaseOldest: sourceDates[0], osmBaseNewest: sourceDates.at(-1),
  attribution: '© OpenStreetMap contributors',
  license: 'ODbL 1.0', licenseUrl: 'https://opendatacommons.org/licenses/odbl/1-0/',
  attributionUrl: 'https://www.openstreetmap.org/copyright',
  coverageNote: 'Partial snapshot of Kochi neighbourhoods. Missing places or categories do not mean none exist. Venue details and opening hours are not verified.',
  bounds: [...new Map(snapshots.filter(s => s.elements.length).map(s => [JSON.stringify(s.bounds), s.bounds])).values()],
  counts: Object.fromEntries(['cafe', 'restaurant', 'cinema', 'theatre', 'nature', 'shopping'].map(id => [id, venues.filter(v => v.categories.includes(id)).length])),
  sources: snapshots.map(s => ({ file: s.file, endpoint: s.endpoint, query: s.query, bounds: s.bounds, fetchedAt: s.fetchedAt, osmBase: s.osm3s?.timestamp_osm_base, elements: s.elements.length })),
};
const output = new URL('../data/kochi.js', import.meta.url);
const temporary = new URL('../data/kochi.js.tmp', import.meta.url);
await writeFile(temporary, '// Generated by scripts/build-kochi.mjs from saved Overpass responses.\n// OpenStreetMap contributors, ODbL 1.0. See kochi-source/README.md.\nexport const KOCHI_CATALOGUE = ' + JSON.stringify({ metadata, venues }, null, 2) + ';\n');
await rename(temporary, output);
console.log(JSON.stringify({ venues: venues.length, categories: metadata.counts, sourceDates: [metadata.osmBaseOldest, metadata.osmBaseNewest], snapshots: snapshots.length }));
